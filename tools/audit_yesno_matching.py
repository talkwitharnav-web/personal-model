"""Can the yes/no answer be predicted WITHOUT understanding the question?

The pairs in `data/yesno` are generated by taking a true sentence and corrupting one slot:

    Was it Jack McKeown who directed Coastlines?      -> No
    Context: Coastlines is a 2002 film ... directed by Victor Nunez.

Notice what is available to a lazy learner. In the *Yes* version every content word of the question
appears in the context, because the question was built from that sentence. In the *No* version the
swapped-in entity ("Jack McKeown") does not appear, because it was imported from somewhere else.

So "is every content word of the question present in the context?" may predict the label outright,
with no comprehension of who directed what. That is a section 9 shortcut of the purest kind, and it
would be invisible to loss, to accuracy on this set, and to a 50/50 label balance check.

This measures the tell directly, and estimates how accurate a model would be using ONLY that rule.
"""
import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

SEPARATOR = "<|endoftext|>"

STOP = set("""a an the is are was were be been being do does did done have has had having
will would shall should can could may might must of in on at to for from by with about as
it its this that these those there here who whom whose which what when where why how and or
but if then than so not no yes correct true false say said says called known also
""".split())


def parse(path, limit):
    rows = []
    buffer, size = [], 0
    with open(path, encoding="utf-8", errors="replace") as handle:
        for line in handle:
            buffer.append(line)
            size += len(line)
            if size > 40_000_000:
                break
    for block in "".join(buffer).split(SEPARATOR):
        block = block.strip()
        if not block:
            continue
        match = re.search(r"\nAssistant:", block)
        if not match:
            continue
        head, answer = block[:match.start()], block[match.end():].strip()
        context = ""
        ctx = re.search(r"\n\s*Context:\s*", head)
        if ctx:
            context = head[ctx.end():].strip()
            head = head[:ctx.start()]
        question = re.sub(r"^User:\s*", "", head).strip()
        rows.append((question, context, answer))
        if len(rows) >= limit:
            break
    return rows


def content_words(text):
    words = re.findall(r"[A-Za-z0-9']+", text.lower())
    return [w for w in words if w not in STOP and len(w) > 1]


def coverage(question, context):
    """Share of the question's content words that appear in the context."""
    words = content_words(question)
    if not words:
        return 1.0
    lowered = context.lower()
    return sum(1 for w in words if w in lowered) / len(words)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--dataset", default="yesno")
    parser.add_argument("--limit", type=int, default=20000)
    args = parser.parse_args()

    path = Path("data") / args.dataset / "train.txt"
    rows = parse(path, args.limit)
    yes = [(q, c) for q, c, a in rows if a.strip().rstrip(".").lower() == "yes"]
    no = [(q, c) for q, c, a in rows if a.strip().rstrip(".").lower() == "no"]
    print(f"{args.dataset}: {len(rows):,} examples | {len(yes):,} Yes | {len(no):,} No\n")
    if not yes or not no:
        print("  not a yes/no dataset - nothing to measure")
        return 0

    cov_yes = [coverage(q, c) for q, c in yes]
    cov_no = [coverage(q, c) for q, c in no]
    mean_yes = sum(cov_yes) / len(cov_yes)
    mean_no = sum(cov_no) / len(cov_no)

    print("How much of the QUESTION is findable in the CONTEXT?")
    print(f"  Yes examples: {mean_yes*100:5.1f}% of content words present")
    print(f"  No  examples: {mean_no*100:5.1f}% of content words present")
    print(f"  gap:          {abs(mean_yes-mean_no)*100:5.1f} points")

    full_yes = sum(1 for c in cov_yes if c >= 0.999) / len(cov_yes)
    full_no = sum(1 for c in cov_no if c >= 0.999) / len(cov_no)
    print(f"\n  every content word present:  Yes {full_yes*100:5.1f}%   No {full_no*100:5.1f}%")

    # A model that ONLY applies the rule "all words present -> Yes, else No".
    correct = sum(1 for c in cov_yes if c >= 0.999) + sum(1 for c in cov_no if c < 0.999)
    accuracy = correct / (len(cov_yes) + len(cov_no))
    print(f"\n  A rule that reads NO MEANING - 'all question words in context -> Yes' - scores")
    print(f"  {accuracy*100:.1f}% on this set. Chance is 50.0%.")

    # The hard rule above understates the risk badly. A network does not learn a brittle
    # "all or nothing" test, it learns a soft threshold on a continuous feature - so the honest
    # measure is the BEST accuracy any single threshold on this one number can achieve.
    best_acc, best_t = 0.0, 0.0
    for step in range(0, 101):
        threshold = step / 100
        hit = sum(1 for c in cov_yes if c >= threshold) + sum(1 for c in cov_no if c < threshold)
        acc = hit / (len(cov_yes) + len(cov_no))
        if acc > best_acc:
            best_acc, best_t = acc, threshold

    # AUC: the chance a random Yes scores above a random No on this feature alone. Threshold-free.
    merged = sorted([(c, 1) for c in cov_yes] + [(c, 0) for c in cov_no])
    rank_sum, i = 0, 0
    while i < len(merged):
        j = i
        while j < len(merged) and merged[j][0] == merged[i][0]:
            j += 1
        average_rank = (i + j + 1) / 2          # 1-based average rank for ties
        rank_sum += sum(average_rank for k in range(i, j) if merged[k][1] == 1)
        i = j
    n_yes, n_no = len(cov_yes), len(cov_no)
    auc = (rank_sum - n_yes * (n_yes + 1) / 2) / (n_yes * n_no)

    print(f"\n  BEST single threshold on that one number: {best_acc*100:.1f}% at cutoff {best_t:.2f}")
    print(f"  AUC of the feature alone: {auc:.3f}   (0.500 = no signal, 1.000 = perfect)")
    accuracy = best_acc

    print("\n" + "=" * 78)
    if accuracy > 0.80:
        print("VERDICT: SHORTCUT. The label is recoverable by string matching alone, so the model\n"
              "can score well without learning what the question asks. This is section 9 again.")
    elif accuracy > 0.65:
        print("VERDICT: PARTIAL shortcut. String matching beats chance by a wide margin; the set\n"
              "teaches some comprehension but rewards matching too.")
    else:
        print("VERDICT: clean. String matching does not recover the label.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
